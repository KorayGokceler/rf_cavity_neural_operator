"""Merge paper/bib/*.bib into paper/references.bib; for a key defined twice the entry with more fields wins."""
import glob
import re

entries, origin = {}, {}
for path in sorted(glob.glob("bib/*.bib")):
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,(.*?)\n\}", text, re.S):
        key, body = m.group(2), m.group(0).strip()
        if key in entries:
            norm = lambda s: re.sub(r"\s+", " ", s)
            if norm(entries[key]) != norm(body):
                nfields = lambda e: len(re.findall(r"^\s*\w+\s*=", e, re.M))
                if nfields(body) > nfields(entries[key]):
                    entries[key], origin[key] = body, path
                print(f"duplicate {key}: kept {origin[key]}")
            continue
        entries[key], origin[key] = body, path
with open("references.bib", "w", encoding="utf-8") as f:
    f.write("% Generated by merge_bib.py from bib/*.bib; edit those files instead.\n\n")
    f.write("\n\n".join(entries[k] for k in sorted(entries)) + "\n")
print(len(entries), "entries")
